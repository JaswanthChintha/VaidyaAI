def merge_stage_warnings(*groups: Iterable[StageWarning]) -> List[StageWarning]:
    """Every warning, origins intact, de-duplicated by (stage, module, message).

    The rule engine and the ML engine both carry the SAME Modules 4-6 warnings
    forward, so a naive concatenation shows each of them twice. De-duplicating
    on the whole triple -- rather than on the message alone -- is what keeps a
    warning that two DIFFERENT stages genuinely raised visible as two entries,
    and keeps the surviving copy stamped with the stage that actually raised
    it rather than with ours.
    """
    return _dedup(
        (w for group in groups for w in group),
        lambda w: (w.stage, w.module, w.message),
    )


def _stage_warnings(messages: Iterable[str]) -> List[StageWarning]:
    return [
        StageWarning(stage=STAGE_DECISIONS, module=DECISIONS_MODULE, message=m)
        for m in messages
    ]


