_SLUG_RE = re.compile(r"[^a-z0-9]+")


def _slug(value: Optional[str]) -> str:
    text = _SLUG_RE.sub("-", (value or "").strip().lower()).strip("-")
    return text or "unknown"


def decision_trace(decision: ClinicalDecision, origin: str) -> Optional[str]:
    """The exact rule id or predictor name behind a decision.

    This is what Module 20 must be able to name when a user asks "why?", so it
    is read from the producer's own metadata rather than reconstructed.
    """
    meta = decision.metadata or {}
    if origin == ORIGIN_RULES:
        value = meta.get("rule_id")
    else:
        value = meta.get("predictor") or meta.get("model_name")
    if value is None:
        value = decision.source
    return str(value) if value is not None else None


def decision_band_label(decision: ClinicalDecision, origin: str) -> Optional[str]:
    """The producer's own user-facing wording for what it concluded.

    Module 8 puts the band's label in `metadata.band_label`
    ("three or more major cardiovascular risk factors were counted"); Module 10
    puts the equivalent in `metadata.band_meaning`. Carrying it verbatim is how
    Module 17 can state what a source actually claimed instead of inferring it
    from a status enum -- which is precisely what the `Heart Disease` hazard
    requires (see `assessment_basis` below).
    """
    meta = decision.metadata or {}
    if origin == ORIGIN_RULES:
        label = meta.get("band_label")
    else:
        label = meta.get("band_meaning") or meta.get("risk_band")
    if label is None:
        return None
    text = str(label).strip()
    return text or None


def assessment_basis(decision: ClinicalDecision, origin: str) -> str:
    """WHICH QUESTION this decision answered.

    THE `Heart Disease` HAZARD, handled without renaming anything.

    `Heart Disease` is emitted by the composite clinical rule from a COUNT OF
    RECORDED RISK FACTORS -- a statement about burden -- and by Module 11's
    predictor as an ESTIMATED LIKELIHOOD -- a statement about probability.
    Renaming either condition would stop them fusing, which would defeat the
    entire point of Module 16. Blending them into one sentence would tell the
    user that a risk-factor tally was a probability.

    So the two keep the same condition and still fuse, but each contribution
    carries the basis it answered on, the fused decision flags the
    disagreement, and Module 17 renders the contributions separately. Module 11
    may override this by setting `metadata["assessment_basis"]`; the default
    for a model is `model_probability`.
    """
    if not decision.was_assessed:
        # An abstention answered no question, so it can never create a
        # conflict with the source that did assess.
        return BASIS_NOT_ASSESSED
    meta = decision.metadata or {}
    declared = meta.get("assessment_basis")
    if isinstance(declared, str) and declared.strip():
        return declared.strip()
    if origin == ORIGIN_RULES:
        if "factors_counted" in meta or "factor_count" in meta:
            return BASIS_RISK_FACTOR_COUNT
        return BASIS_THRESHOLD
    return BASIS_MODEL_PROBABILITY


def _assign_ids(records: List[Tuple[str, ClinicalDecision]]) -> List[str]:
    """Deterministic ids: ``<origin>:<condition>:<trace>`` plus ``#n`` on a tie.

    A tie happens when one rule id legitimately produces two decisions, or when
    a producer records no rule id at all. The suffix keeps ids unique without
    making them random, so two runs over the same input produce the same ids
    and a reviewer can diff them.
    """
    used: Dict[str, int] = {}
    ids: List[str] = []
    for origin, decision in records:
        base = (
            f"{origin}:{_slug(decision.condition)}:"
            f"{_slug(decision_trace(decision, origin))}"
        )
        count = used.get(base, 0) + 1
        used[base] = count
        ids.append(base if count == 1 else f"{base}#{count}")
    return ids


