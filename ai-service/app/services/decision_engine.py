class _SourceResult:
    __slots__ = ("data", "summary")

    def __init__(self, data: Any, summary: SourceRunSummary) -> None:
        self.data = data
        self.summary = summary


def _run_source(
    name: str,
    module: int,
    kind: DecisionSourceKind,
    call,
    warnings: List[str],
    failure_message: str,
) -> _SourceResult:
    """Call one decision source with its failure CONTAINED, not propagated.

    A source that raises must not take down the analysis of every other source.
    The failure becomes a warning plus `failed=True`, which carries no
    decisions at all -- so it cannot be mistaken for "assessed and nothing
    found", and Module 16 will not invent a fused decision for a condition
    nobody assessed.
    """
    try:
        data = call()
    except Exception as exc:  # noqa: BLE001 - contained deliberately
        # Type only in the log. An exception message can echo input values,
        # which are medical data and must never reach the logs.
        logger.error(
            "decision_source_failed %s",
            safe_meta(source=name, error_type=type(exc).__name__),
        )
        warnings.append(failure_message)
        return _SourceResult(
            None,
            SourceRunSummary(
                name=name,
                module=module,
                kind=kind,
                ran=False,
                failed=True,
                error_type=type(exc).__name__,
                decision_count=0,
            ),
        )
    decisions = list(getattr(data, "decisions", ()) or ())
    return _SourceResult(
        data,
        SourceRunSummary(
            name=name,
            module=module,
            kind=kind,
            ran=True,
            failed=False,
            decision_count=len(decisions),
        ),
    )


