class MergedFields:
    """The result of merging a set of decisions, before it is given a source."""

    __slots__ = (
        "status",
        "risk",
        "confidence",
        "confidence_basis",
        "evidence",
        "recommendations",
        "assessed",
        "unassessed",
    )

    def __init__(
        self,
        status: DecisionStatus,
        risk: Optional[RiskLevel],
        confidence: Optional[float],
        confidence_basis: str,
        evidence: List[EvidenceItem],
        recommendations: List[Recommendation],
        assessed: List[ClinicalDecision],
        unassessed: List[ClinicalDecision],
    ) -> None:
        self.status = status
        self.risk = risk
        self.confidence = confidence
        self.confidence_basis = confidence_basis
        self.evidence = evidence
        self.recommendations = recommendations
        self.assessed = assessed
        self.unassessed = unassessed


CONFIDENCE_NONE_PRODUCED = "none_produced"
CONFIDENCE_MAX_PROBABILITY = "max_of_model_probabilities"

CONFIDENCE_RULE = (
    "'The strongest available confidence' is the MAXIMUM over the contributing "
    "decisions that actually produced a probability. A decision whose "
    "confidence is None produces no probability at all (a deterministic rule) "
    "and is therefore ABSENT from the maximum -- it is never read as 0.0, and "
    "it never suppresses a real probability from another source. A decision "
    "whose confidence is 0.0 DID produce a probability and does take part, so "
    "a fused confidence of 0.0 is a real, confident negative and is distinct "
    "from None. When no contributor produced a probability the fused "
    "confidence is None, never 0.0."
)


def merge_decision_set(decisions: Sequence[ClinicalDecision]) -> MergedFields:
    """Merge a set of decisions ABOUT ONE CONDITION into consolidated fields.

    Spec Module 16 points 2-5, implemented once and shared by the
    within-source merge (Module 15) and the cross-source fusion (Module 16).

    RISK -- `RiskLevel.highest()`, which is the type's own ordering. Note it
    returns None for an empty list rather than LOW, so "nothing assessed" can
    never become "low risk".

    CONFIDENCE -- see `CONFIDENCE_RULE`. `None` and `0.0` are NOT conflated.

    STATUS -- see `STATUS_FUSION_RULE`.

    EVIDENCE -- de-duplicated by `EvidenceItem.dedup_key()`, first occurrence
    wins, order preserved. Evidence is taken from the ASSESSED decisions only
    whenever at least one decision assessed the condition. An unassessed
    decision's evidence says "this value was not available in the submitted
    report" about the very features an assessed decision has just quoted a
    value for; showing both would put a contradiction in front of the reader.
    The unassessed decision is not lost -- it stays in the collection, in
    `unassessed_sources`, and in its own contribution record. When NOTHING
    assessed, the evidence IS the list of what was missing, so it is kept.

    RECOMMENDATIONS -- de-duplicated by `Recommendation.dedup_key()` (the
    catalogue code) and taken from EVERY decision, assessed or not. The
    asymmetry with evidence is deliberate: evidence is a claim about a value
    and can contradict, whereas "one analysis could not be completed, consider
    a repeat test" remains true and actionable alongside a finding that did
    come out. Recommendations are only ever unioned here, never invented --
    fusion cannot introduce advice that was not already approved upstream.
    """
    assessed = [d for d in decisions if d.was_assessed]
    unassessed = [d for d in decisions if not d.was_assessed]

    if assessed:
        risk = RiskLevel.highest([d.risk for d in assessed if d.risk is not None])
        if risk is None:
            # Unreachable while `ClinicalDecision` enforces "assessed => risk",
            # but if that invariant were ever relaxed, silently emitting an
            # assessed status with no risk would leave Modules 16 and 19 with
            # nothing to prioritise on. Degrade honestly instead.
            status = DecisionStatus.INSUFFICIENT_DATA
        else:
            status = max(
                assessed, key=lambda d: _STATUS_SEVERITY[d.status]
            ).status
    else:
        risk = None
        status = DecisionStatus.INSUFFICIENT_DATA

    probabilities = [d.confidence for d in decisions if d.confidence is not None]
    if probabilities and status is not DecisionStatus.INSUFFICIENT_DATA:
        confidence: Optional[float] = max(probabilities)
        confidence_basis = CONFIDENCE_MAX_PROBABILITY
    else:
        # Nothing assessed => no probability can describe the result, whatever
        # a contributor happened to carry.
        confidence = None
        confidence_basis = CONFIDENCE_NONE_PRODUCED

    evidence_sources = assessed if assessed else list(decisions)
    evidence = _dedup(
        (item for d in evidence_sources for item in d.evidence),
        lambda item: item.dedup_key(),
    )
    recommendations = _dedup(
        (rec for d in decisions for rec in d.recommendations),
        lambda rec: rec.dedup_key(),
    )

    return MergedFields(
        status=status,
        risk=risk,
        confidence=confidence,
        confidence_basis=confidence_basis,
        evidence=evidence,
        recommendations=recommendations,
        assessed=assessed,
        unassessed=unassessed,
    )


def _dedup(items: Iterable[Any], key) -> List[Any]:
    """First occurrence wins, order preserved."""
    seen: Dict[Any, None] = {}
    out: List[Any] = []
    for item in items:
        k = key(item)
        if k in seen:
            continue
        seen[k] = None
        out.append(item)
    return out


def unique(values: Iterable[Any]) -> List[Any]:
    """De-duplicate preserving order. The one place `sources` is made unique."""
    return _dedup(values, lambda v: v)


