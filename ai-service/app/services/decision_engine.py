"""Module 15 -- the Decision Engine.

    evaluate_rules()  ─┐
                       ├─>  collect_decisions()  ─>  fuse_decisions()  ─>  17
    predict_all()     ─┘         Module 15              Module 16

Spec Module 15: the Decision Engine "collects decisions generated by the
Clinical Rule Engine, the Diabetes / Heart / Kidney predictors and future
predictors. It acts as an intermediate decision management layer before
fusion."

Framework-independent: no FastAPI, no I/O of its own, no global state beyond
the ML registry it is handed. Module 17 will call `collect_decisions()`
in-process exactly as it calls `evaluate_rules()` and `predict_all()`.

==========================================================================
THE FOUR THINGS THIS LAYER GUARANTEES
==========================================================================

1. ONE SOURCE FAILING NEVER LOSES THE OTHER'S DECISIONS. Each source is called
   inside its own guard, and the failure becomes a `SourceRunSummary` with
   `failed=True` plus a warning. `backend/` already learned this lesson: a bare
   `Promise.all` over rules and ML would discard a good result because the
   other one raised. The same shape is enforced here, in-process, so a caller
   that bypasses the backend gets the same resilience.

2. NO UPSTREAM WARNING IS EVER DROPPED. Modules 4, 5, 6, 8 and 9/10 warnings
   are carried through with `{stage, module, message}` intact, de-duplicated by
   that whole triple so a warning BOTH sources relayed appears once WITH ITS
   ORIGINAL ORIGIN rather than being re-stamped as ours. Dropping upstream
   warnings has been a real defect twice on this project.

3. EVERY DECISION GETS A STABLE ID. Deterministic, derived from origin +
   condition + rule id / predictor name. Same input, same ids, every run. A
   UUID would make the grouping unauditable and would make Module 20's "trace
   this finding back to the exact rule" impossible to verify in a test.

4. DECISIONS ARE GROUPED BY ``(condition, source)`` BEFORE FUSION. See the
   docstring of `app/schemas/fusion.py` for why this is Module 15's job and not
   Module 8's: the rule engine correctly emits one decision PER RULE, and
   fusion must still see one entry per source.

==========================================================================
WHAT MERGING TWO DECISIONS FROM ONE SOURCE MEANS
==========================================================================

The within-source merge uses the SAME core as Module 16's cross-source fusion
(`merge_decision_set` below) -- risk takes the highest, status takes the most
severe assessed value, evidence and recommendations are unioned. Two
implementations would eventually disagree, and the disagreement would be
invisible: both would return a well-formed `ClinicalDecision`.

What it does NOT do is change the source kind. Merging two rule decisions
yields a rule decision, not a hybrid one. Only Module 16 may emit
`source_kind=FUSION`.
"""

